import test from 'node:test';
import assert from 'node:assert/strict';
test('H09 Claude adapter binds identity, pushes hints only and requires explicit acknowledgement', async () => {
  const { createClaudeBridge } = await import('../lib/hub/claude.js');
  const calls = [], notifications = [];
  const message = { id: 'm1', text: 'private task body', from: { name: 'alice' }, claimToken: 'claim', recovery: false };
  const client = { rpc: async (op, args) => { calls.push({ op, args }); if (op === 'inbox.peek') return { ok: true, messages: [{ id: 'm1' }] }; if (op === 'inbox.claim') return { ok: true, messages: [message] }; return { ok: true, text: 'accepted' }; } };
  const bridge = createClaudeBridge({ client, sessionId: 'claude-bound', notify: async n => notifications.push(n) });
  await bridge.wake(); await bridge.wake();
  assert.equal(notifications.length, 1); assert.equal(notifications[0].method, 'notifications/claude/channel');
  assert.equal(JSON.stringify(notifications).includes(message.text), false);
  const inbox = await bridge.call('peer_inbox', {}); assert.match(JSON.stringify(inbox), /private task body/);
  assert.equal(calls.some(c => c.op === 'inbox.ack'), false);
  await bridge.call('peer_ack', { messageIds: ['m1'] }); assert.equal(calls.at(-1).args.stage, 'consumed');
  await bridge.call('peer_request', { from: 'spoof', operationId: 'spoof', to: 'alice', text: 'work' });
  assert.equal(calls.at(-1).args.from, 'claude-bound'); assert.notEqual(calls.at(-1).args.operationId, 'spoof');
  message.recovery = true;
  assert.doesNotMatch(JSON.stringify(await bridge.call('peer_inbox', {})), /private task body/);
  assert.equal((await bridge.call('peer_ack', { messageIds: ['m1'] })).ok, false);
  assert.equal((await bridge.call('admin.inspect', {})).ok, false);
});
